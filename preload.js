const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('native', {
  host: port => ipcRenderer.invoke('host', port),
  steamStatus: () => ipcRenderer.invoke('steam:status'),
  steamInvite: () => ipcRenderer.invoke('steam:invite'),
  steamPending: () => ipcRenderer.invoke('steam:pending'),
  onSteamJoin: cb => { if (typeof cb === 'function') ipcRenderer.on('steam:join', (e, r) => cb(r && typeof r === 'object' ? { ok: !!r.ok, port: r.port | 0, error: String(r.error || '') } : null)); },   // resolves { ok, token } for the host's own game window only
  setPresence: p => ipcRenderer.invoke('presence', p && typeof p === 'object' ? { details: String(p.details || ''), state: String(p.state || ''), cat: String(p.cat || ''), join: String(p.join || ''), party: p.party && typeof p.party === 'object' ? { id: String(p.party.id || ''), n: p.party.n | 0, max: p.party.max | 0 } : null } : null),
  discordPending: () => ipcRenderer.invoke('discord:pending'),
  onDiscordJoin: cb => { if (typeof cb === 'function') ipcRenderer.on('discord:join', (e, s) => cb(String(s || ''))); },
  stop: () => ipcRenderer.invoke('stop'),
  quit: () => ipcRenderer.invoke('app:quit'),
  setWindowMode: m => ipcRenderer.invoke('win:mode', m === 'borderless' ? 'borderless' : 'windowed'),
  getWindowMode: () => ipcRenderer.invoke('win:getmode'),
  setAspect: r => ipcRenderer.invoke('win:aspect', +r || 0),
  ips: () => ipcRenderer.invoke('ips'),
  publicIp: () => ipcRenderer.invoke('publicIp'),
  texStatus: () => ipcRenderer.invoke('tex:status'),
  platform: process.platform,
  gpuStatus: () => ipcRenderer.invoke('gpu:status'),
  gpuSet: (m, k, a) => ipcRenderer.invoke('gpu:set', m, k, a),
  gpuRestart: () => ipcRenderer.invoke('gpu:restart'),
  fpsUnlock: v => ipcRenderer.invoke('fps:unlock', typeof v === 'number' ? v : (v ? 999 : 0)),
  fbList: (d, a) => ipcRenderer.invoke('fb:list', d, a),
  fbRead: f => ipcRenderer.invoke('fb:read', f),
  profileRead: () => ipcRenderer.invoke('profile:read'),
  profileWrite: t => ipcRenderer.invoke('profile:write', t),
  backupRead: n => ipcRenderer.invoke('backup:read', n),
  pickFile: accept => ipcRenderer.invoke('pick:file', accept),
  texChoose: () => ipcRenderer.invoke('tex:choose'),
  texClear: () => ipcRenderer.invoke('tex:clear'),
  modelBounds: names => ipcRenderer.invoke('tex:models', names),
  modelMeshes: names => ipcRenderer.invoke('tex:meshes', names),
  texLoad: names => ipcRenderer.invoke('tex:load', names),
  mcStatus: () => ipcRenderer.invoke('mc:status'),
  mcChoose: () => ipcRenderer.invoke('mc:choose'),
  mcClear: () => ipcRenderer.invoke('mc:clear'),
  mcLoad: keys => ipcRenderer.invoke('mc:load', keys)
});
